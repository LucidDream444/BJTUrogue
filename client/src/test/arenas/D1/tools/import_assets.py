"""Deterministic import; preserve originals, infer no animation from folder numbers."""
from pathlib import Path
from PIL import Image
import re,json,shutil,hashlib,argparse
p=argparse.ArgumentParser();p.add_argument('--source',default='D:/课后勇者');args=p.parse_args()
base=Path(args.source); client=Path(__file__).resolve().parents[5]
names={'1':'player_student_sword','2':'player_student_shoot','4':'player_student_run_gun','8':'player_student_run'}
dirs=['overview','nw','n','ne','e','w','sw','s','se']; entries=[]; anims=[]; art=[]; rows=[]
for group in ['1','2','3','4','5','6','8']:
 files=sorted((base/group).rglob('*.png'))
 tres=next((base/group).rglob('*.tres'),None)
 text=tres.read_text() if tres else ''
 for index,src in enumerate(files):
  im=Image.open(src).convert('RGBA'); w,h=im.size
  key=names.get(group) or ('player_student_idle_'+dirs[index] if group=='3' else 'ui_campus_'+('pixel_board' if group=='5' else 'fantasy_board'))
  fw={'1':76,'2':72,'4':71,'8':64}.get(group,w); fh=fw if tres else h
  target=('ui/d1/' if group in ['5','6'] else 'sprites/player/')+key+'.png'
  dest=client/'public/assets'/target; dest.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(src,dest)
  count=(w//fw)*(h//fh); kind='spritesheet' if tres else 'image'
  e=dict(key=key,path=target,placeholder=False,kind=kind,width=fw,height=fh)
  if tres:e.update(frameWidth=fw,frameHeight=fh)
  entries.append(e)
  anchors=[]
  for i in range(count):
   frame=im.crop(((i%(w//fw))*fw,(i//(w//fw))*fh,(i%(w//fw)+1)*fw,(i//(w//fw)+1)*fh))
   bb=frame.getbbox() or (0,0,fw,fh); bottom=bb[3]
   feet=[x for y in range(max(0,bottom-4),bottom) for x in range(fw) if frame.getpixel((x,y))[3]>128]
   anchors.append([round((min(feet)+max(feet)+1)/2/fw,5) if feet else .5,round(bottom/fh,5)])
  a=dict(key=key,group=group,frameWidth=fw,frameHeight=fh,count=count,anchors=anchors,source=str(src.relative_to(base)),sha256=hashlib.sha256(src.read_bytes()).hexdigest())
  if tres:
   # All supplied exports have duration=1 and speed=8: exactly 125 ms per frame.
   assert set(re.findall(r'"duration": ([\d.]+)',text))=={'1.0'}
   assert set(re.findall(r'"speed": ([\d.]+)',text))=={'8.0'}
   assert count==(16 if group in names else 1)
   anims.append(dict(animKey=key+'_export',textureKey=key,frames=list(range(count)),frameRate=8,repeat=-1))
  art.append(a)
  rows.append(f'| `{a["source"]}` | `{w}×{h}` | `{fw}×{fh}` / '+('0–15 行优先；8fps；每帧125ms；循环' if count==16 else '单帧；8fps；125ms；循环' if tres else '静态 Sprite2D')+f' | `{target}` |')
output='// Generated by D1/tools/import_assets.py; reviewed visual roles, original PNGs unchanged.\nimport type { AssetEntry, AnimDef } from \'./assetManifest\'\n'
output+='export const D1_ASSETS: readonly AssetEntry[] = '+json.dumps(entries,ensure_ascii=False,indent=2)+'\n'
output+='export const D1_ANIMS: readonly AnimDef[] = '+json.dumps(anims,ensure_ascii=False,indent=2)+'\n'
output+='export const D1_ART = '+json.dumps(art,ensure_ascii=False,indent=2)+' as const\n'
(client/'src/core/d1AssetManifest.ts').write_text(output,encoding='utf8')
(client/'src/test/arenas/D1/ASSET_MAPPING.md').write_text('# 原素材映射（逐 PNG）\n\n原始文件保留且客户端副本 SHA256 相同。Godot centered=false 仅表示导出左上原点；Phaser 战斗使用各帧脚底锚点，物理体独立。全部源PNG/TRES/TSCN已检查。\n\n| 原文件（相对素材根） | 实际图片尺寸 | 裁切与时序 | 客户端新路径（assets/） |\n|---|---|---|---|\n'+'\n'.join(rows)+'\n\n## 视觉识别与用途\n\n1：同方向挥剑序列，资源展示播放，不给三种枪增加未设计的近战伤害。\n2：同方向持枪射击序列，战斗原地攻击。\n4：同方向持枪跑动序列，战斗移动攻击。\n8：同方向徒手跑动序列，普通移动。\n3 overview：八方向3×3总览，192×192整图是一个帧，不当角色动画；其余依次 NW/N/NE/E/W/SW/S/SE，各自是64×64单帧，用于待机方向选择。侧向/斜向为视觉判断，保留原图可复核。\n5：像素校园UI整图；6：幻想校园UI整图。未提供可复用控件的精确裁切规范，均在预览展示，等待D4切图，不充当人物。\n\n## 缺失与替代表现\n\n没有专用受击、死亡动画。受击沿用当前动作加红白闪光，逻辑时间窗口只在有效伤害发生时设置；死亡使用最后帧倾斜/降暗。移动与射击仅右向序列，左向水平翻转；上下瞄准由独立枪管指示，角色保持侧向，这是明确的临时表现。\n\n原始导出所有 duration=1.0、speed=8.0、loop=true；统一 ANIMS 注册为8fps/repeat=-1，逐帧125ms，没有变速丢失。运行时仅加载 PNG；玩家按 GameClock 取对应注册动画的帧，保证暂停、顿帧不继续播放。脚底锚点按每帧底部4行非透明像素范围中点确定，原始透明边距不参与碰撞。\n',encoding='utf8')
print('Imported',len(entries),'PNG files; registered',len(anims),'animations')
