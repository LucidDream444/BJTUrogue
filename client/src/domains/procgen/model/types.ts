/**
 * 按 `id` 取房间。
 *
 * 抛而不是返回 `undefined`：`id` 来自平面图配置表，取不到就说明
 * **问的这个 id 不属于这一层**（打错了，或者问的是走廊）—— 那是调用方的 bug。
 * 静默返回 `undefined` 只会把错误推迟到某个 `?.` 吞掉的地方。
 */
export function roomById(map: DungeonMap, id: string): Room {
  const room = map.rooms.find((r) => r.id === id)
  if (room === undefined) {
    const ids = map.rooms.map((r) => r.id).join(', ')
    throw new Error(`地图里没有 id 为「${id}」的房间（这一层有：${ids}）`)
  }
  return room
}

/** 按 `order`（= 在 `rooms` 里的下标）取房间。取不到就抛，理由同上。 */
export function roomByOrder(map: DungeonMap, order: number): Room {
  const room = map.rooms[order]
  if (!room || room.order !== order) {
    throw new Error(`地图里没有 order=${order} 的房间（共 ${map.rooms.length} 间）`)
  }
  return room
}