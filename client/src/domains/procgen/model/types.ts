// ---------------------------------------------------------------- 几何

/**
 * 轴对齐矩形。**`x` / `y` 是中心点**，与 `ArenaBase` 的 `WallSpec` 一致。
 *
 * 中心点约定不是随便选的：`ArenaBase.makeNav()` 与 `isWalkable()` 用的都是
 * 「格子中心点落在矩形里才算堵」，两处若各用各的原点约定，症状是
 * 「看着能过的门口过不去」，而且**只在有墙的场子里出现**。
 */
export interface Rect {
  readonly x: number
  readonly y: number
  readonly width: number
  readonly height: number
}

export interface Point {
  readonly x: number
  readonly y: number
}

// ---------------------------------------------------------------- 障碍物

/**
 * 室内障碍物的种类。**它决定的是「挡不挡子弹」，不是「挡不挡路」** ——
 * 两种在寻路网格上完全一样（都不可走），差异只在子弹碰撞上。
 *
 * D1 依据 `kind` 决定把它放进哪个碰撞分组。生成侧只需要把种类写对。
 */
export type ObstacleKind =
  /** 课桌。挡路 + **挡子弹** */
  | 'desk'
  /** 椅子。挡路 + **不挡子弹**（子弹穿过去继续飞） */
  | 'chair'

/**
 * 室内障碍物。玩家与怪物 MUST NOT 能穿过它。
 *
 * 尺寸契约：课桌**宽是区间** `deskWidthCells ~ deskWidthCellsMax` 格（配表里是 2~4，
 * **每组桌椅各抽一次** —— 见 `gen/obstacles.ts` 的 `rng.between`）、高恒为
 * `deskHeightCells` 格（配表里是 1），**只横竖**、按格对齐；椅子恒为 1 格。
 * ⚠️ 这里原写「恒为 `deskWidthCells × deskHeightCells`（配表里是 2×1）」—— 那是
 * 2026-10-15 的旧契约（桌恒 2 格），10-16 起就换成了区间（`docs/地牢生成设计.md`
 * 是 v1.3 · 2026-10-15 的那一版，§三 里的「2×1 / 组外框 2×2」同样过时）。
 * 照旧读数写代码的症状：D1 拼家具时把桌宽当成常数 2，而图里有大量 3、4 格的桌。
 * **"可视 = 可走性"** ——
 * 一张看着能挤过去的缝，寻路也必须认为能过去。按格对齐正是为了消掉
 * 「看着能过、实际整格封死」的错位。
 *
 * ⚠️ **桌椅是成组的**（schemaVersion 4 起）：每一张 `'desk'` 的正下方紧贴着一把 `'chair'`，
 * 而且椅子横向落在桌子那一跨里。地图里**没有**「组」这个字段 —— 组是从这一条几何关系
 * **读**出来的（`model/furniture.ts` 的 `furnitureUnits()`）。存一个字段就多一个真值来源，
 * 而两个来源分岔的那天不会报错，只会有一张桌子的椅子画歪。
 */
export interface Obstacle {
  readonly kind: ObstacleKind
  readonly rect: Rect
}

// ---------------------------------------------------------------- 门

/**
 * 一扇门 —— 也就是墙上的一段**缺口**，连着两个空间。
 *
 * 门段本身**不是障碍物**：它表达的是"这里可以出去"。战斗期间关门是 D1 的场景逻辑
 * （把缺口填上一块可碰撞的矩形），D2 只负责把门的位置和两端写对。
 *
 * ## 无向：`a` / `b` 按字典序排好
 *
 * 门**没有「来」与「去」**（旧模型的 `back` / `forward` / `side` 三态与
 * `toOrder` 都随「不回头」规则一起作废了）。两个字段都是 **id**：
 * `Room.id`（`'YF604'`）或走廊段的 id（`'C_M'`），所以门可以连到走廊 ——
 * **这一版的 16 扇门全部都是「房间 ↔ 走廊」**。
 *
 * 排序是**为了让「同一扇门」在任何两处读起来逐字相同**，不是语义的一部分：
 * 不排的话，同一扇门在生成器里是 `(YF601, C_W)`、在校验器里是 `(C_W, YF601)`，
 * 而两者相等与否要靠人去比 —— 那种相等迟早会被 `===` 判错，且不报错。
 */
export interface Door {
  /** 门洞段的中心 */
  readonly x: number
  readonly y: number
  /** 门洞的宽度（沿着墙的方向量） */
  readonly width: number
  /**
   * 门开在哪一堵墙上，也就是人**穿过它的方向**：
   *
   * - `'h'`：开在一堵水平墙上 → 人沿 **y** 方向穿过
   * - `'v'`：开在一堵竖直墙上 → 人沿 **x** 方向穿过
   */
  readonly axis: 'h' | 'v'
  /** 这一头是哪个空间（`Room.id` 或走廊段 id）。字典序较小的一头 */
  readonly a: string
  /** 另一头。字典序较大的一头 */
  readonly b: string
}

// ---------------------------------------------------------------- 房间

/**
 * 一间房：教室、楼梯间都是它。走廊**不是**（见 `Passage`）。
 *
 * ## `id` 是身份，`order` 只是**稳定显示序**
 *
 * - `id`（`'YF604'` / `'STAIR'`）来自平面图配置表，是这个空间**唯一的名字**。
 *   「谁发过奖励没有」「进没进过这间」这类问题一律按 `id` 问 ——
 *   名字不会因为地图里多了一间房而变。
 * - `order` 是**它在 `map.rooms` 里的下标**，0 起连号、升序 = 楼梯间 + 其余按 `id` 升序。
 *   留着它是因为小地图、D1 的 `stage` 编号这些地方要一个**整数**键。
 *
 * ⚠️ **`order` 不再是进度轴。** v4 及以前它是「走到第几间了」，`order` 越大越深；
 * v5 里玩家随意挑房间进，`order` 大不代表更深、也不代表「更后面」。
 * **任何按 `order` 大小推出来的结论都是错的**（v4 的 `leavesBehind` 就是这么写的）。
 */
export interface Room {
  /** 平面图上的名字（`'YF604'` / `'STAIR'`）。**身份，不是显示文案** */
  readonly id: string
  /** 在 `map.rooms` 里的下标。`0` 恒为楼梯间（`start`）。**不是进度** */
  readonly order: number
  readonly kind: RoomKind
  readonly rect: Rect
  /**
   * 开在**这间房**身上的门。
   *
   * 一扇「房间 ↔ 走廊」的门只出现在那一间房这里；将来真出现「房间 ↔ 房间」的门，
   * 它会在两间房的 `doors` 里各出现一次（`gen/layout.ts` 按「谁在门的两端」建这个数组）。
   * 两侧都记是必要的：`obstacles.ts` 的门前净空只读**这间房自己的** `doors`，
   * 少记一侧，那一侧的课桌就会大摇大摆地堵在门前面，而洞口在数据里看着完好无损。
   */
  readonly doors: readonly Door[]
  readonly obstacles: readonly Obstacle[]
  /** 刷怪点。**每一个都从门可达** —— 这是由构造保证的，见 design D5 */
  readonly spawnPoints: readonly Point[]
  /**
   * 威胁预算。**与难度档位无关**；难度只乘在「预算 → 具体刷怪」那一步。
   *
   * 它按**到楼梯间的 BFS 跳数**参数化（`gen/budget.ts`）：离出生点越远越强。
   * 旧模型用的是「主干序号 ÷ 主干数」，那条式子的立足点（主干轴）随 v5 一起没了。
   *
   * **非战斗关别恒为 `0`** —— 一个空场地写着一份威胁预算就是数据在说谎。
   * 哪几类关别要打由配置表的 `combatKinds` 决定（`isCombatKind()`）。
   */
  readonly budget: number
}

// ---------------------------------------------------------------- 地图

/**
 * `DungeonMap.schemaVersion` 当前值。**改字段语义时加一**（红线 3）。
 *
 * - `1`：首版。主干道是一条贯穿全层的 `corridorRect`，主干教室南北交替挂在它两侧。
 * - `2`：平面结构返工成「**一排主干教室 + 连廊**」—— `corridorRect` 换成 `passages`。
 *   见 `openspec/changes/rework-layout-to-classroom-row`。
 * - `3`：**侧室的 `kind` 说真话** —— 由一律 `'main'` 改为按关别抽（精英 / 道具 / 宝箱），
 *   非战斗关别不摆桌椅、不刷怪、预算为 0；`RoomKind` 增第 8 类 `'chest'`。
 *   见 `openspec/changes/room-kinds-and-furniture`。
 * - `4`：**课桌换了形状、桌椅成了组**。v3 的课桌是「1 格宽 × 2—4 格长的横条」，
 *   椅子按 `chairChance` 随机撒；v4 照 D1 三张手绘关里的家具关系改成
 *   「2×1 格的桌 + 正下方紧贴的 1 格椅子」，椅子必有。见 `model/furniture.ts`。
 * - `5`：**几何从「算」改成「画」**，`Room` / `Door` / `Passage` 三个类型同时变形。
 *   见 `openspec/changes/real-floorplan-layout` 与本次的文件头。这是**语义变化**
 *   而不是单纯的新增字段：同一串 `rooms` 在 v4 里是一条进度轴上的教室
 *   （`order` 越大越深、`branch` 说它在不在主干上），在 v5 里是一张平面图上的
 *   16 间平权的房（`order` 只是下标、`id` 才是身份）；同一扇 `Door` 在 v4 里
 *   是有向的 `toOrder`，在 v5 里是**无向**的 `a` / `b`。**按 v4 的理解去读 v5
 *   的数据会得到错的答案，而且不报错。**
 */
export const DUNGEON_SCHEMA_VERSION = 5

/**
 * 一段**走廊**。走廊是一张**网**，不是主干道，也不是「教室之间的连廊」。
 *
 * 玩家在走廊里随意走、随意挑一间房进（用户 2026-10-19：「不要之前的主干道样式了，
 * 可以随意在走廊走，随意选择房间进入挑战」）。所以：
 *
 * - **段数不必凑成某个数。** v2—v4 里它是「教室之间的一小段」，数目恒为 `主干数 − 1`；
 *   v5 里段与段直接相接、拼成什么形状由平面图说了算（今天 6 段，S 形）。
 * - **段与段之间不隔墙**（平面图里「相邻空间空出 1 格」那条规则的唯一例外，
 *   因为它们本来就是同一条走廊）。
 *
 * ⚠️ **`rect` 是纯可走区域**（与房间同约定：格跨度直接就是矩形）。
 * v2—v4 的 `Passage.rect` **含墙**（墙骑在它的上下两条边上、各吃半层），
 * 拿它当可走区域会少算两格 —— 而少掉的那两格正好是**墙**。
 * 这条约定在 v5 反过来了：**走廊矩形与房间矩形都是「可走的那一片」**，
 * 墙是它们**之间**空出来的那些格子（见 `DungeonMap.walls`）。
 *
 * ⚠️ **名字里的 `passages`（连廊）是 v2 的遗留**，改名的代价落在 D1 的消费点上，
 * 而本次已经是一次 BREAKING —— 一起改会让通知里那张表长一倍。所以名字先留着、
 * 语义按注释走：**v5 的 `passages` = 走廊段**。
 */
export interface Passage {
  /** 平面图上的走廊段 id（`'C_W'` / `'C_J'` / `'C_M'` …） */
  readonly id: string
  readonly rect: Rect
}

/**
 * 一层楼。**生成器的产物、D1 战斗场景的输入、D2 校验器的输入，同一个形状。**
 */
export interface DungeonMap {
  /** 本地存档/数据迁移用（红线 3）。缺了校验器直接报错 */
  readonly schemaVersion: number
  readonly seed: number
  /**
   * 整层的外框（px、中心点）。缩略图与相机的取景依据。
   *
   * ⚠️ v4 的 `bounds` 是**墙**的包围盒（外墙比房间边界还往外半个墙厚）；
   * v5 不是 —— 墙现在比房间还要往外铺整整 2 格（见 `walls`），
   * 拿墙去算包围盒会让地图四周凭空多出一圈。
   *
   * ★ 改了（2026-10-22 晚）：它是平面图里**声明**的 `footprint`（`FloorPlan.bounds`
   * 由它换算），**不再是「全部房间与走廊的并集」**。两者在 6F / 3F 上恰好相等，
   * 在 1F 上**不相等**：1F 的房间从 `y25` 起，楼的最北一条带在那一层是实心墙。
   * 三层的外框必须逐格一样（换层时 `BattleScene.applyArena()` 对账），
   * 所以它不能跟着「最靠边的那间房」走。
   */
  readonly bounds: Rect
  /**
   * **这一层的每一段走廊**，顺序同 `floor-plan.json` 的 `corridors`。
   *
   * 走廊**不是 `Room`**：不计入房间总数、没有关别、没有预算、不刷怪、不参与清房判定。
   * 玩家在走廊里永远处于脱离战斗的状态。
   */
  readonly passages: readonly Passage[]
  /**
   * **每一格「不是空间、也不是门洞」的地方**，全在这里。
   *
   * 这是 v5 对 `walls` 的定义，和 v4 完全不是一回事，所以值得逐条说清：
   *
   * - v4：一堵墙 = 房间或侧室的一条**边**，减去门洞。墙是「房间的边界」，
   *   房间之外的地方不在数据里。
   * - v5：墙 = **平面图上所有没被任何空间占用的格子**（减去门洞那几格）。
   *   它既包括房间之间那 1 格的薄墙，也包括被省略掉的电梯、卫生间、
   *   另外 5 处楼梯间这些**整块的实心区**（`floor-plan.json` 的 `_source.simplified` ③）。
   *
   * 为什么非得这样：`buildGrid` 只把「墙 + 障碍物」标成不可走，**其余一律可走**。
   * 于是「不是空间的地方」必须**每一格都出现在 `walls` 里**，少一格就是一个洞 ——
   * 玩家能从 YF601 与 YF602 之间那 22 格实心块里穿过去，而那个块在缩略图上看
   * 跟墙一模一样。**不报错，只是能穿墙。**
   *
   * 墙还**向外多铺 2 格**（`navExtentFor` 给的余量）：不铺的话，贴着地图边缘的房间
   * 与走廊（`C_W` 就在 x = 0 那一列上）会直接开在网格外沿上，玩家一步走出地图。
   *
   * 为什么墙是数据而不是让两边各自从 `rooms` 推导：D1 要它建物理碰撞体
   * （玩家撞墙、子弹被墙吃掉），D2/D3 的寻路要它判可走性。两处各推导一次，
   * 就是那句「同一个事实写两遍，迟早不一致」—— 而这里的表现恰好又是
   * **没有任何报错**的那种：一边推出来的墙少一段，玩家从缝里走出去了，
   * 或者怪卡在一个看不见的角里。
   */
  readonly walls: readonly Rect[]
  /** 全部房间。**按 `order` 升序** —— 顺序就是「楼梯间 + 其余按 id 升序」 */
  readonly rooms: readonly Room[]
  /**
   * 寻路网格的格边长（px）。**放进地图数据，不是各场景各选一个。**
   *
   * 这是 D2 最在意的一个字段。校验器与运行时 MUST 用同一份可走性判定，
   * 而"同一份判定"最容易被破坏的方式就是两边用了不同的 `cellSize` ——
   * 那时 1000 个种子全绿、运行时某个刷怪点被封死，**两边都不抛异常**，
   * 症状是"怪不出来、房间清不掉"。
   * 写进数据里，两侧就物理上不可能各选一个值。
   */
  readonly navCellSize: number
  /** 寻路网格的**最小角**（不是格子中心偏移，见 `ArenaBase.makeNav` 的 ⚠️） */
  readonly navOrigin: Point
  /** 这次生成花了多少毫秒。**仅供观测**，不参与任何判定 */
  readonly elapsedMs: number
}

