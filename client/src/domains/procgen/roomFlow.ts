/**
 * **房间的转接判据**：这一间还要不要打、打完了没有、这一扇门现在该不该关着。
 *
 * 纯函数，零 Phaser 依赖（与 `colliders.ts` / `walkability.ts` 同一个层次、同一个理由：
 * 这些判断必须在没有浏览器的环境里可测）。
 *
 * ## 它管的三件事
 *
 * | 问题 | 函数 |
 * |---|---|
 * | 这一间要不要打 | `roomNeedsFight` |
 * | 打完了没有 | `roomCleared` |
 * | 这一扇门现在该不该关着 | `doorShouldBeClosed` |
 *
 * ## ★ v5 删掉了第四件：`leavesBehind`（「不回头」）
 *
 * v4 及以前有一条规则：**走过的房间回不去**，判据是「门两端房间号里小的那个
 * 比玩家现在所在的小，这扇门就关死了」（`Math.min(ownerOrder, toOrder) < currentOrder`）。
 * 它在 v5 **整个不成立**，有两层理由，缺一不可：
 *
 * 1. **它读的那个顺序没了**。`Room.order` 现在是「楼梯间 + 其余按 id 升序」的
 *    **显示序**，不是进度轴（`model/types.ts` 的 `Room.order` 那条 ⚠️ 原话：
 *    「任何按 `order` 大小推出来的结论都是错的」）。`leavesBehind` 正是那样的结论。
 * 2. **用户要的就是能回头**：「可以随意在走廊走，随意选择房间进入挑战」——
 *    走廊是可走的常去之处，进门出门本来就该是自由的。
 *
 * 门本身也跟着变了：v5 的门**无向**（`Door.a` / `b` 按字典序排好，没有「来」与「去」），
 * 而「不回头」的前提正是「门有前后两侧」。所以它连输入都凑不出来。
 *
 * ⚠️ **删它不等于「门永远开着」** —— 下面那条「正在战斗」仍然关着门，理由不一样
 * （不是玩法规则，是清房判定成立的前提）。
 *
 * ## `combatKinds` 与 `spawnPoints` 取「或」
 *
 * 「这一间打不打」有两个来源，它们说的不是一件事：
 *
 * - `combatKinds`（配置）说的是**这一类关别该不该打** —— 语义
 * - `spawnPoints`（地图）说的是**这一间实际有没有怪** —— 事实
 *
 * 正常情况两者一致；不一致时**以「没有出生点」为准**。理由是不对称的代价：
 * 把一间本该打的房放过去，玩家少打一场；把一间没怪的房锁上，玩家被关在里面
 * —— 没有怪可打，门永远不会开。
 *
 * ## 两条真存在的「不一致」，都不是假设
 *
 * - **非战斗关别却有空房**：`gen/spawns.ts` 对非战斗关别**早返回空数组**
 *   （`layout.ts` 也把预算写成 0）。今天它们本来就一致，
 *   但一条只认 `combatKinds` 的实现会在关别表改动的第一天把道具关变成牢房。
 * - **战斗关别却没有怪**：同一份 `gen/spawns.ts` 在**一个格都挑不出来**时
 *   也返回空数组（`candidates.length === 0`）。这不是理论分支 —— 它是那条
 *   「怪站不进去就只能给空房」的兜底，而 `validate/contract.ts` **只拒绝反方向**
 *   （非战斗房**有**刷怪点），这一头它管不着。
 *
 * 所以「或」不是为了将来，是为了今天就已经存在的那条路径。
 */

import type { RoomsConfig } from './config'
import { isCombatKind } from './config'
import type { Room } from './model/types'

/**
 * 这一间要不要打。
 *
 * `false` 的房间**一进场就算已清**（于是它从不进 `doorShouldBeClosed` 的 `combatRooms`，
 * 门一直开着）—— 不这么做的话，道具关 / 宝箱关会把玩家关在里面：它们没有出生点，
 * 照「清完才开门」的字面执行，门永远不会开。
 */
export function roomNeedsFight(room: Room, cfg: RoomsConfig): boolean {
  return isCombatKind(cfg, room.kind) && room.spawnPoints.length > 0
}

/**
 * 这一间打完了没有。
 *
 * 两个输入都必须是**现在还活着 / 还没出来的数量**，只看存活是不够的：
 *
 * - 队列里排着一只还没出生的怪时，房间看起来是空的 —— 门提前打开，
 *   玩家走进隔壁，那只怪随后出生在身后的空房里。表现为「有一间永远清不掉」。
 * - 最后一只怪是**分裂怪**时还有第二段延迟：子代既不在存活里、也还没进队列。
 *   那一段**从 `EnemySystem` 的公开面看不到**，所以调用方要额外拿一个
 *   时间窗口兜住它（见 `docs/地牢生成设计.md` 与本次 change 的 design）。
 *
 * 这里只做算术：两个数都到 0 才算清。**时间窗口不在这条判据里** ——
 * 判据是纯的，等多久是调度的事。
 */
export function roomCleared(liveInRoom: number, queuedInRoom: number): boolean {
  return liveInRoom <= 0 && queuedInRoom <= 0
}

/** 判「这一扇门现在该不该关着」的输入。 */
export interface DoorStateInput {
  /** 门洞开在**哪一间**的墙上 —— 和 `DoorBarrier.ownerOrder` 同一个编号 */
  readonly ownerOrder: number
  /**
   * 现在**正在战斗**的那些房间 —— `Room.order` 的集合。
   *
   * 传集合而不是传一个 `boolean`，是为了让调用方（场景）手上只有一份真值：
   * 场景每帧算一次「哪几间在战斗」，然后拿任意一扇门去问。
   * 传布尔值的话，调用方得自己先找到「这扇门属谁」，两处查找迟早对不上。
   */
  readonly combatRooms: ReadonlySet<number>
}

/**
 * 这一扇门现在该不该关着。
 *
 * ## v5 之后**只剩一条理由**：这一间正在战斗
 *
 * | 理由 | 什么时候成立 | v5 |
 * |---|---|---|
 * | 尽头 | 门外是墙外，本来就没地方可去 | **没了** |
 * | 落在身后 | 「不回头」 | **删了**，见文件头 |
 * | 正在战斗 | 这一间要打、且没清完 | **还在** |
 *
 * 前两条消失都不是「换个写法」，是它们要描述的东西不存在了：
 *
 * - **尽头**：v5 的 16 扇门**全是「房间 ↔ 走廊」**，走廊是可走的实体空间
 *   （`Passage` 有自己的 `rect`），不是「墙外」。所以「门外没地方可去」
 *   这一情形在本层**一扇门都对不上**。（v4 的 `toOrder === null` 说的是
 *   「门开在整张地图的外框上」，而那种门在 v5 的生成器里根本不会被造出来。）
 * - **落在身后**：见文件头那段。
 *
 * ## 为什么「正在战斗」这一条必须留着
 *
 * 它不只是玩法（怪不该跑出去），它是**清房判定成立的前提**：
 * 只有怪出不去，「本房间敌人全部死亡」才是一个可判定的条件，而不是「差不多能判」。
 * 删掉它，`roomCleared` 就从「判据」退化成「猜测」。
 *
 * 推论：**没在战斗的房间，门一定是开的** —— 没进过的房间、打完的房间、
 * 以及道具关 / 宝箱关这类 `roomNeedsFight` 为假、一进场就算已清的房间。
 * 玩家因此可以随意在走廊走、随意挑一间进去打。
 *
 * ⚠️ 走廊**永远不会**进 `combatRooms`：里面不刷怪（`gen/spawns.ts` 只往房间里放），
 * 所以「隔壁走廊正在战斗」不会把这一扇门关上。
 *
 * ⚠️ 这里判的是**门该是什么状态**，不是「谁来把它变成那个状态」。
 * 挡板的开关是场景的事（`colliders.ts` 里那条：「开关状态不在数据里、也不该在」）。
 */
export function doorShouldBeClosed(input: DoorStateInput): boolean {
  return input.combatRooms.has(input.ownerOrder)
}